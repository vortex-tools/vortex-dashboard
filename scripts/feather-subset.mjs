// Writes src/components/base/featherIcons.ts: the Feather icons the app
// names (any quoted string in src/ that is an icon name), from
// feather-icons-react's icons.json - instead of bundling all ~290.
// Run after using a new icon: `node scripts/feather-subset.mjs`.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const all = JSON.parse(
  readFileSync('node_modules/feather-icons-react/build/icons.json', 'utf8')
);
const out = 'src/components/base/featherIcons.ts';
const files = [];
const walk = d => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(tsx?|jsx?)$/.test(f) && p !== out) files.push(p);
  }
};
walk('src');
const used = new Set();
for (const f of files)
  for (const [, s] of readFileSync(f, 'utf8').matchAll(
    /['"`]([a-z0-9-]+)['"`]/g
  ))
    if (all[s]) used.add(s);
const names = [...used].sort();
writeFileSync(
  out,
  `// Generated by scripts/feather-subset.mjs - do not edit.\n// The Feather icons the app uses (${names.length} of ${Object.keys(all).length}).\nconst ICONS: Record<string, string> = {\n${names.map(n => `  ${JSON.stringify(n)}: ${JSON.stringify(all[n])}`).join(',\n')}\n};\nexport default ICONS;\n`
);
console.log(`${names.length} icons -> ${out}`);
